// Builds src-tauri/lists/scriptlets.js: uBlock Origin's scriptlets + the scriptlet rules from uBO's filter lists,
// as ONE self-contained script that Hush injects at document start (desktop: initialization script,
// Android: addDocumentStartJavaScript). It looks up the page's hostname and runs only the matching scriptlets.
// This is what makes YouTube and anti-adblock sites work.
//
// Source code and lists: uBlock Origin (GPLv3) — github.com/gorhill/uBlock, github.com/uBlockOrigin/uAssets.
// Usage: node tools/build-scriptlets.mjs <uBlock checkout> <uAssets gh-pages checkout>
import fs from 'fs';
import path from 'path';
import { pathToFileURL, fileURLToPath } from 'url';

const [ublock, uassets] = process.argv.slice(2);
if (!ublock || !uassets) { console.error('usage: node tools/build-scriptlets.mjs <uBlock> <uAssets gh-pages>'); process.exit(1); }
const imp = p => import(pathToFileURL(path.join(ublock, p)).href);
const { builtinScriptlets } = await imp('src/js/resources/scriptlets.js');
const sfp = await imp('src/js/static-filtering-parser.js');

// 1) Scriptlet functions (main-world only), keyed by token; aliases resolved to the real name.
const fns = new Map(), alias = new Map();
for (const s of builtinScriptlets) {
  const name = s.name.replace(/\.js$/, '');
  for (const a of s.aliases || []) alias.set(a.replace(/\.js$/, ''), name);
  if (s.world === 'ISOLATED') continue;
  fns.set(name, { code: s.fn.toString(), call: s.fn.name, deps: (s.dependencies || []).map(d => d.replace(/\.js$/, '')) });
}
const canon = n => alias.get(n.replace(/\.js$/, '')) || n.replace(/\.js$/, '');

// 2) Scriptlet rules from uBO's lists. "+[args]" = run, "-[args]" = exception/negation, "-[]" = disable all.
const LISTS = ['filters/filters.min.txt', 'filters/quick-fixes.min.txt', 'filters/unbreak.min.txt', 'filters/privacy.min.txt'];
const parser = new sfp.AstFilterParser({ trustedSource: true });
const rules = new Map();
const add = (hn, v) => { if (!rules.has(hn)) rules.set(hn, new Set()); rules.get(hn).add(v); };
let n = 0;
for (const list of LISTS) {
  const file = path.join(uassets, list);
  if (!fs.existsSync(file)) { console.warn('missing', file); continue; }
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!line.includes('+js(')) continue;
    parser.parse(line);
    if (!parser.isScriptletFilter() || parser.hasError?.()) continue;
    const args = parser.getScriptletArgs();
    const exc = parser.isException();
    if (args.length) args[0] = canon(args[0]);
    if (args.length && !fns.has(args[0])) continue;           // unknown or isolated-world scriptlet
    const json = JSON.stringify(args);
    if (!parser.hasOptions()) { if (exc) add('*', '-' + json); continue; }   // only exceptions may be generic
    for (const d of parser.getExtFilterDomainIterator()) {
      const { hn, not, bad } = { ...d };
      if (bad || (exc && not) || !hn || hn.startsWith('/')) continue;
      add(hn, (exc || not ? '-' : '+') + json); n++;
    }
  }
}

// 3) Keep only functions reachable from used scriptlets.
const used = new Set();
const visit = name => { if (used.has(name) || !fns.has(name)) return; used.add(name); fns.get(name).deps.forEach(visit); };
for (const set of rules.values()) for (const v of set) { const a = JSON.parse(v.slice(1)); if (a.length) visit(a[0]); }
const callable = [...used].filter(k => !k.endsWith('.fn'));

// Compact encoding: unique rule strings in S; hosts that share the same rule set grouped on one line ",h1,h2,|i,j".
const S = [], sIdx = new Map(), groups = new Map();
for (const [hn, set] of rules) {
  const ix = [...set].map(v => { if (!sIdx.has(v)) { sIdx.set(v, S.length); S.push(v); } return sIdx.get(v); }).sort((x, y) => x - y).join(',');
  if (!groups.has(ix)) groups.set(ix, []); groups.get(ix).push(hn);
}
const H = '\n' + [...groups].map(([ix, hosts]) => ',' + hosts.join(',') + ',|' + ix).join('\n') + '\n';
const out = `// Generated by tools/build-scriptlets.mjs from uBlock Origin (GPLv3). Do not edit by hand.
(function hushScriptlets() {
if (window.__hushScriptlets) return; window.__hushScriptlets = true;
const off = (window.__hushOff || []);
const hn0 = location.hostname; if (!hn0) return;
if (off.some(h => hn0 === h || hn0.endsWith('.' + h))) return;
const H = ${JSON.stringify(H)};
const S = ${JSON.stringify(S)};
const look = k => { const out = [], needle = ',' + k + ','; let p = 0;
  while ((p = H.indexOf(needle, p)) >= 0) { const b = H.lastIndexOf('\\n', p), e = H.indexOf('\\n', p), bar = H.indexOf('|', p);
    if (bar > 0 && bar < e) H.slice(bar + 1, e).split(',').forEach(i => out.push(S[+i])); p = e; }
  return out; };
const hns = [hn0]; for (let p = 0; (p = hn0.indexOf('.', p) + 1) > 0;) hns.push(hn0.slice(p));
const ens = []; for (let h of hns) { for (let i; (i = h.lastIndexOf('.')) > 0;) { h = h.slice(0, i); ens.push(h + '.*'); } }
const run = new Set(), skip = new Set();
for (const k of [...hns, ...ens, '*']) for (const v of look(k)) (v[0] === '+' ? run : skip).add(v.slice(1));
if (skip.has('[]') || run.size === 0) return;
const scriptletGlobals = {};
${[...used].map(k => fns.get(k).code).join('\n')}
const F = { ${callable.map(k => JSON.stringify(k) + ': ' + fns.get(k).call).join(', ')} };
for (const j of run) { if (skip.has(j)) continue; try { const a = JSON.parse(j); const f = F[a[0]]; if (f) f(...a.slice(1)); } catch (e) {} }
})();
`;
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src-tauri/lists/scriptlets.js');   // works on Windows too
fs.writeFileSync(dest, out);
console.log(`${n} scriptlet rules on ${rules.size} hosts, ${used.size} functions -> ${dest} (${(out.length / 1024).toFixed(0)} KB)`);
